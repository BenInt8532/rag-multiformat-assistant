"""
Тексты промптов ассистента.
Собраны в одном месте: менять формулировки можно, не трогая остальной код.
"""

import re
from typing import Any, Dict, List, Tuple

# Ответ, когда ни один чанк не прошёл отбор: модель при этом не вызывается
NO_CONTEXT_ANSWER = "В документах нет информации по этому вопросу."

SYSTEM_PROMPT = (
    "Ты отвечаешь на вопросы по документам. Единственный источник сведений - фрагменты "
    "документов из сообщения пользователя. Собственные знания не используй."
)

# Фраза отказа в правиле 2 совпадает с NO_CONTEXT_ANSWER: отказы можно считать автоматически
USER_PROMPT = """Фрагменты документов:

{context}

Вопрос: {question}

Правила ответа:
1. Отвечай только тем, что прямо написано во фрагментах.
2. Если ответа во фрагментах нет, напиши ровно: «""" + NO_CONTEXT_ANSWER + """»
3. Число, срок или условие относи только к тому, для чего оно указано во фрагменте. Не переноси его на другие страны, офферы и случаи.
4. Если для ответа нужно число, а в тексте стоит имя переменной или настройки (например, MAX_ITEMS), сначала найди во фрагментах строку, где этому имени присвоено значение (вида MAX_ITEMS = 50), и назови это число. Только если такой строки нет ни в одном фрагменте, назови имя и прямо напиши: «его значение во фрагментах не указано».
5. Отвечай по-русски полным предложением, без вступлений.
6. Последней строкой напиши «Источники:» и номера фрагментов, из которых взят ответ, например: Источники: [1], [3]. При отказе по правилу 2 эту строку не пиши."""

# Номера фрагментов в конце ответа модели (правило 6). Модель пишет их и отдельной строкой,
# и в той же строке после ответа, с точкой в конце: «...7 дней. Источники: [1], [2].»
SOURCES_TAIL = re.compile(r"\s*источники?\s*:\s*((?:\[?\s*\d+\s*\]?[\s,;и]*)+)\.?\s*$", re.IGNORECASE)


def split_sources(answer: str, chunks: List[Dict[str, Any]]) -> Tuple[str, List[str]]:
    """
    Отделение хвоста «Источники: [1], [3]» от текста ответа.

    Модель называет номера фрагментов, а имена файлов подставляет код:
    так имя файла не искажается и не попадает в текст, который оценивает судья.

    Args:
        answer: ответ модели как есть
        chunks: чанки контекста в том порядке, в котором они шли в промпте

    Returns:
        текст ответа без строки источников и имена файлов названных фрагментов (без повторов)
    """
    match = SOURCES_TAIL.search(answer)
    if not match:
        return answer.strip(), []

    files: List[str] = []
    for number in re.findall(r"\d+", match.group(1)):
        position = int(number) - 1
        # Номер, которого в промпте не было, пропускается
        if 0 <= position < len(chunks) and chunks[position]["source"] not in files:
            files.append(chunks[position]["source"])
    return answer[:match.start()].strip(), files


def build_messages(question: str, chunks: List[Dict[str, Any]]) -> List[Dict[str, str]]:
    """
    Сообщения для модели: системная часть и вопрос с фрагментами документов.

    Args:
        question: вопрос пользователя
        chunks: чанки, отобранные в контекст; у каждого text и source

    Returns:
        список сообщений в формате OpenAI
    """
    context = "\n".join(
        f"[{number}] файл: {chunk['source']}\n{chunk['text']}\n"
        for number, chunk in enumerate(chunks, 1)
    )
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": USER_PROMPT.format(context=context, question=question)}
    ]
